       CASE WHEN b.room_no = '201' AND b.bed_no = '1' THEN 'ICU' ELSE 'NORMAL' END,
       CASE WHEN b.room_no = '201' AND b.bed_no = '1' THEN 500.00 ELSE 80.00 END
