    SELECT 1 AS dept_id FROM dual UNION ALL SELECT 2 FROM dual UNION ALL SELECT 3 FROM dual UNION ALL SELECT 4 FROM dual UNION ALL
    SELECT 5 FROM dual UNION ALL SELECT 6 FROM dual UNION ALL SELECT 7 FROM dual UNION ALL SELECT 8 FROM dual UNION ALL
    SELECT 9 FROM dual UNION ALL SELECT 10 FROM dual UNION ALL SELECT 11 FROM dual UNION ALL SELECT 12 FROM dual UNION ALL
    SELECT 13 FROM dual UNION ALL SELECT 14 FROM dual
) d
CROSS JOIN (
    SELECT '101' AS room_no, '1' AS bed_no FROM dual UNION ALL
    SELECT '101','2' FROM dual UNION ALL SELECT '101','3' FROM dual UNION ALL
