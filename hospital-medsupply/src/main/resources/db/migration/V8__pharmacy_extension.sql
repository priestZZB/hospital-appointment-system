--   B1 药品三分类；B5 药库批次效期；B6 退药；B7 调拨；
--   B8 麻精管控+五专登记；B9 CDSS 规则；B10 抗菌授权；B3 代煎订单
-- 方言：Oracle 19c（IDENTITY/VARCHAR2 CHAR/TIMESTAMP DEFAULT SYSDATE）
