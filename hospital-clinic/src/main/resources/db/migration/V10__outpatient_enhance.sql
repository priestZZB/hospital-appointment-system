-- ==================== 6. schedule_generate_log 自动排班 Job 日志（A8） ====================
DECLARE v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'SCHEDULE_GENERATE_LOG';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE TABLE schedule_generate_log (
        id            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
        biz_date      DATE                NOT NULL,
        created_count NUMBER(10)          DEFAULT 0,
        message       VARCHAR2(500 CHAR)  DEFAULT NULL,
        create_time   TIMESTAMP           DEFAULT SYSDATE NOT NULL,
        CONSTRAINT pk_schedule_generate_log PRIMARY KEY (id)
    )'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IDX_SGL_BIZ_DATE';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_sgl_biz_date ON schedule_generate_log (biz_date)'; END IF;
END;
/
COMMENT ON TABLE schedule_generate_log IS '自动排班 Job 执行日志（每日凌晨自动生成未来第 7 天排班）';
COMMENT ON COLUMN schedule_generate_log.biz_date IS '本次生成目标出诊日期';
COMMENT ON COLUMN schedule_generate_log.created_count IS '本次实际新建排班数量';
COMMENT ON COLUMN schedule_generate_log.message IS '执行结果说明（跳过数量、失败原因等）';
