-- clinic_db V10：门诊流程补强（迭代9 A1~A8 / J3）
-- 说明：
--   1. checkin 增加分诊字段：priority（0=急诊 1=优先 2=普通）、
--      return_flag（回诊标记）、triage_nurse_id / triage_time（分诊操作留痕）
--   2. slot 增加 channel_type（NORMAL 普通号源 / GREEN 绿色通道号源：
--      老年/军人/急诊优先）与 overbook（该号源是否允许加号超挂）
--   3. schedule 增加 fee_type（NORMAL 普通 / EXPERT 专家号分层定价）
--      与 overbook（排班维度加号开关）
--   4. appointment 增加 overbook_flag（加号预约标记）
--   5. 新表 icd_dict：ICD-10 诊断字典（J3 病历诊断编码校验）
--   6. 新表 schedule_generate_log：自动排班 Job 执行日志（A8）
--   幂等说明：Oracle 无 ADD COLUMN IF NOT EXISTS / CREATE TABLE IF NOT EXISTS，
--   全部结构变更收敛进 PL/SQL 块按 user_tables/user_tab_columns/user_indexes
--   探测后再 EXECUTE IMMEDIATE，可安全重复执行（Flyway 重跑 / 手工补跑均无害）。
-- =============================================================

-- ==================== 1. checkin 分诊字段（A1/A6） ====================
DECLARE v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM user_tab_columns WHERE table_name = 'CHECKIN' AND column_name = 'PRIORITY';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE checkin ADD (priority NUMBER(3) DEFAULT 2 NOT NULL)'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_tab_columns WHERE table_name = 'CHECKIN' AND column_name = 'RETURN_FLAG';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE checkin ADD (return_flag NUMBER(3) DEFAULT 0 NOT NULL)'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_tab_columns WHERE table_name = 'CHECKIN' AND column_name = 'TRIAGE_NURSE_ID';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE checkin ADD (triage_nurse_id NUMBER(19) DEFAULT NULL)'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_tab_columns WHERE table_name = 'CHECKIN' AND column_name = 'TRIAGE_TIME';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE checkin ADD (triage_time TIMESTAMP DEFAULT NULL)'; END IF;
END;
/
COMMENT ON COLUMN checkin.priority IS '分诊优先级: 0-急诊 / 1-优先 / 2-普通（默认普通）';
COMMENT ON COLUMN checkin.return_flag IS '回诊标记: 0-初诊排队 / 1-检查检验完成回诊（同档优先插队）';
COMMENT ON COLUMN checkin.triage_nurse_id IS '分诊操作护士用户ID（auth sys_user.id）';
COMMENT ON COLUMN checkin.triage_time IS '分诊操作时间';

