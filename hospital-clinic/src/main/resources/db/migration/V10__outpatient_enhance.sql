-- ==================== 5. icd_dict ICD-10 诊断字典（J3） ====================
DECLARE v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'ICD_DICT';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE TABLE icd_dict (
        id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
        icd_code    VARCHAR2(20 CHAR)   NOT NULL,
        icd_name    VARCHAR2(200 CHAR)  NOT NULL,
        category    VARCHAR2(50 CHAR)   DEFAULT NULL,
        is_common   NUMBER(3)           DEFAULT 0,
        status      NUMBER(3)           DEFAULT 1,
        create_time TIMESTAMP           DEFAULT SYSDATE NOT NULL,
        CONSTRAINT pk_icd_dict PRIMARY KEY (id),
        CONSTRAINT uk_icd_dict_code UNIQUE (icd_code)
    )'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IDX_ICD_DICT_NAME';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_icd_dict_name ON icd_dict (icd_name)'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IDX_ICD_DICT_CATEGORY';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_icd_dict_category ON icd_dict (category)'; END IF;
    SELECT COUNT(*) INTO v_cnt FROM user_indexes WHERE index_name = 'IDX_ICD_DICT_COMMON';
    IF v_cnt = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_icd_dict_common ON icd_dict (is_common)'; END IF;
END;
/
COMMENT ON TABLE icd_dict IS 'ICD-10 诊断字典（病历诊断编码校验依据）';
COMMENT ON COLUMN icd_dict.icd_code IS 'ICD-10 编码（唯一，如 I10.x05 / E11）';
COMMENT ON COLUMN icd_dict.icd_name IS '诊断标准名称（中文规范名）';
COMMENT ON COLUMN icd_dict.category IS 'ICD 章节分类（如 循环系统/呼吸系统）';
COMMENT ON COLUMN icd_dict.is_common IS '常用标记: 0-普通 / 1-常用（录入联想优先展示）';
COMMENT ON COLUMN icd_dict.status IS '状态: 1-启用 / 0-停用';

